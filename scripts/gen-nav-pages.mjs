// Generates src/lib/nav-pages.generated.ts from the <Item href label> entries in
// src/components/sidebar.tsx so the role page-permission list stays in sync with navigation.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sidebarPath = join(root, 'src/components/sidebar.tsx');
const outPath = join(root, 'src/lib/nav-pages.generated.ts');

const src = readFileSync(sidebarPath, 'utf8');
const desktopEnd = src.indexOf('{/* Mobile drawer */}');
const socialStart = src.indexOf('function SocialNav');
const scanned =
  (desktopEnd > 0 ? src.slice(0, desktopEnd) : src) + '\n' + (socialStart > 0 ? src.slice(socialStart) : '');

const headerRe = /tracking-widest[^>]*>([^<]+)<\/div>/;
const itemRe = /<Item\s+href="([^"]+)".*?\slabel="([^"]+)"/;

const groups = [];
const byName = new Map();
let current = 'General';
for (const line of scanned.split('\n')) {
  const h = line.match(headerRe);
  if (h) {
    current = h[1].trim();
    continue;
  }
  const m = line.match(itemRe);
  if (!m) continue;
  const [, href, label] = m;
  const path = href.split('?')[0];
  const key = path.replace(/^\//, '').replace(/\//g, '.');
  let g = byName.get(current);
  if (!g) {
    g = { module: current, pages: [] };
    byName.set(current, g);
    groups.push(g);
  }
  if (!g.pages.some((p) => p.key === key)) g.pages.push({ key, path, label });
}

const total = groups.reduce((n, g) => n + g.pages.length, 0);
if (total === 0) {
  console.warn('[gen-nav-pages] no sidebar items found; keeping existing file');
  if (!existsSync(outPath)) process.exit(1);
  process.exit(0);
}

const body = `// AUTO-GENERATED by scripts/gen-nav-pages.mjs from src/components/sidebar.tsx. Do not edit by hand.
export type NavPage = { key: string; path: string; label: string };
export type NavModule = { module: string; pages: NavPage[] };

export const NAV_MODULES: NavModule[] = ${JSON.stringify(groups, null, 2)};
`;
writeFileSync(outPath, body);
console.log(`[gen-nav-pages] ${total} pages in ${groups.length} modules`);
