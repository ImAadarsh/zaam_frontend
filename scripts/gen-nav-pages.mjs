// Generates src/lib/nav-pages.generated.ts from the <Item href label> entries in
// src/components/sidebar.tsx so the role page-permission list stays in sync with navigation.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sidebarPath = join(root, 'src/components/sidebar.tsx');
const outPath = join(root, 'src/lib/nav-pages.generated.ts');

const src = readFileSync(sidebarPath, 'utf8');
const desktopEnd = src.indexOf('{/* Mobile drawer */}');
const socialStart = src.indexOf('function SocialNav');
const scanned =
  (desktopEnd > 0 ? src.slice(0, desktopEnd) : src) + '\n' + (socialStart > 0 ? src.slice(socialStart) : '');

const headerRe = /tracking-widest[^>]*>([^<]+)<\/div>/;
const itemRe = /<Item\s+href="([^"]+)".*?\slabel="([^"]+)"/;
const hasRoleRe = /hasRole\(\[([^\]]*)\]\)\s*&&/;
const roleCheckRe = /useRoleCheck\(\[([^\]]*)\]/;

const parseRoles = (list) => list.split(',').map((r) => r.trim().replace(/['"]/g, '').toUpperCase()).filter(Boolean);

/** Roles the page's own useRoleCheck guard admits; null when the page has no role guard. */
function pageGuardRoles(path) {
  const file = join(root, 'src/app', path, 'page.tsx');
  if (!existsSync(file)) return null;
  const m = readFileSync(file, 'utf8').match(roleCheckRe);
  return m ? parseRoles(m[1]) : null;
}

/**
 * Built-in roles that can open a page today: the sidebar hasRole() gate and the page's
 * useRoleCheck() gate both apply. Omitted when any signed-in user can open it.
 */
function builtInRoles(sidebarRoles, path) {
  const guard = pageGuardRoles(path);
  if (!sidebarRoles && !guard) return undefined;
  if (!sidebarRoles) return guard;
  if (!guard) return sidebarRoles;
  return sidebarRoles.filter((r) => guard.includes(r));
}

const groups = [];
const byName = new Map();
let current = 'General';
let gateRoles = null;
for (const line of scanned.split('\n')) {
  const h = line.match(headerRe);
  if (h) {
    current = h[1].trim();
    continue;
  }
  const gate = line.match(hasRoleRe);
  if (gate) {
    gateRoles = parseRoles(gate[1]);
    continue;
  }
  if (/^\s*\)\}\s*$/.test(line)) {
    gateRoles = null;
    continue;
  }
  const m = line.match(itemRe);
  if (!m) continue;
  const [, href, label] = m;
  const path = href.split('?')[0];
  const key = path.replace(/^\//, '').replace(/\//g, '.');
  let g = byName.get(current);
  if (!g) {
    g = { module: current, pages: [] };
    byName.set(current, g);
    groups.push(g);
  }
  if (!g.pages.some((p) => p.key === key)) {
    const roles = builtInRoles(gateRoles, path);
    g.pages.push(roles ? { key, path, label, roles } : { key, path, label });
  }
}

// A module Overview (/<module>/dashboard) is only useful to roles holding another page in that module.
const allPages = groups.flatMap((g) => g.pages);
for (const dash of allPages) {
  const rootSeg = dash.path.split('/')[1];
  if (dash.path !== `/${rootSeg}/dashboard`) continue;
  const others = allPages.filter((p) => p.path.split('/')[1] === rootSeg && p.path !== dash.path);
  if (others.length === 0 || others.some((p) => !p.roles)) continue;
  const moduleRoles = Array.from(new Set(others.flatMap((p) => p.roles)));
  dash.roles = dash.roles ? dash.roles.filter((r) => moduleRoles.includes(r)) : moduleRoles;
}

const total = groups.reduce((n, g) => n + g.pages.length, 0);
if (total === 0) {
  console.warn('[gen-nav-pages] no sidebar items found; keeping existing file');
  if (!existsSync(outPath)) process.exit(1);
  process.exit(0);
}

const body = `// AUTO-GENERATED by scripts/gen-nav-pages.mjs from src/components/sidebar.tsx. Do not edit by hand.
/** roles: built-in role codes that can open the page (SUPER_ADMIN always can); omitted = any signed-in user. */
export type NavPage = { key: string; path: string; label: string; roles?: string[] };
export type NavModule = { module: string; pages: NavPage[] };

export const NAV_MODULES: NavModule[] = ${JSON.stringify(groups, null, 2)};
`;
writeFileSync(outPath, body);
console.log(`[gen-nav-pages] ${total} pages in ${groups.length} modules`);
